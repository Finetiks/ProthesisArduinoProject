#pragma once
/*
 * Gestures.h — бібліотека жестів кисті.
 *
 * Жест описаний не одним фіксованим положенням, а *парою* положень для кожного
 * пальця: де палець стоїть при нульовому стиску (`openPct`) і де — при повному
 * (`closedPct`). Фактична позиція — лінійна інтерполяція між ними за рівнем
 * хвату 0..1000, який дає EMG або джойстик.
 *
 * Це дає одразу три речі безкоштовно:
 *   • пропорційність — хват доводиться рівно настільки, наскільки напружено м'яз;
 *   • «нерухомі» пальці — якщо open == closed, палець просто тримає форму
 *     (так працює вказівний жест і жест-гак);
 *   • переднатяг — палець може стартувати вже підігнутим (боковий хват «ключ»).
 *
 * Таблиця лежить у PROGMEM: на ATmega328P всього 2 КБ RAM, і тримати там
 * статичні дані немає сенсу.
 */

#include <Arduino.h>
#include "Config.h"

/** Максимальна довжина назви жесту в байтах UTF-8, з нуль-термінатором. */
constexpr uint8_t GESTURE_NAME_SIZE = 18;

struct Gesture {
  char    name[GESTURE_NAME_SIZE];
  uint8_t openPct[FINGER_COUNT];   ///< позиція пальця при хваті 0 %
  uint8_t closedPct[FINGER_COUNT]; ///< позиція пальця при хваті 100 %
};

namespace Gestures {

/** Скільки жестів у бібліотеці. */
uint8_t count();

/** Скопіювати опис жесту з PROGMEM у RAM. Індекс за межами таблиці згортається по колу. */
void get(uint8_t index, Gesture& out);

/** Назва жесту в буфер користувача (щоб не тримати копію всієї таблиці в RAM). */
void name(uint8_t index, char* buffer, uint8_t bufferSize);

/**
 * Цільове положення пальця для заданого рівня хвату.
 * @param grip 0..EMG_SCALE
 * @return відсоток стиску 0..100
 */
uint8_t closureFor(const Gesture& gesture, uint8_t finger, uint16_t grip);

/** Наступний/попередній жест по колу — для перемикання жестом м'яза чи джойстиком. */
uint8_t nextIndex(uint8_t index);
uint8_t prevIndex(uint8_t index);

} // namespace Gestures
